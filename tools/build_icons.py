RENDER_SIZE = 512  # render lon roi resize xuong khi dung -> luon sac


def main():
    from playwright.sync_api import sync_playwright

    chrome = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
    ua = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
          "(KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36")

    with sync_playwright() as pw:
        b = pw.chromium.launch(headless=True, executable_path=chrome)
        ctx = b.new_context(user_agent=ua, device_scale_factor=1)
        page = ctx.new_page()

        for name, paths in ICONS.items():
            vb = VIEWBOX[name]
            parts = "".join(
                f'<path fill-rule="{fr}" d="{d}"/>' for d, fr in paths)
            html = f"""<!doctype html><html><head><meta charset="utf-8">
            <style>html,body{{margin:0;padding:0;background:transparent}}</style>
            </head><body>
            <svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}"
                 width="{RENDER_SIZE}" height="{RENDER_SIZE}"
                 fill="#000000">{parts}</svg>
            </body></html>"""
            page.set_content(html)
            page.wait_for_timeout(60)
            el = page.query_selector("svg")
            el.screenshot(path=os.path.join(OUT, f"{name}.png"), omit_background=True)
            print(f"  {name}.png")

        b.close()

    with open(os.path.join(OUT, "meta.json"), "w", encoding="utf-8") as f:
        json.dump({"viewbox": VIEWBOX, "render_size": RENDER_SIZE}, f, indent=1)
    print(f"\nXong! {len(ICONS)} icon -> {OUT}")


if __name__ == "__main__":
    main()
